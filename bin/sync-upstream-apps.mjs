#!/usr/bin/env node
/*
  Keep the auxiliary (non-rareBit) apps this loader serves in step with their
  upstream maintainers in espruino/BangleApps, without merging the whole repo.

    node bin/sync-upstream-apps.mjs            # report only
    node bin/sync-upstream-apps.mjs --pull     # report, then pull what is stale
    node bin/sync-upstream-apps.mjs --pull --app setting --app widbt
    node bin/sync-upstream-apps.mjs --all      # ignore versions, refresh everything

  Files are fetched from raw.githubusercontent.com, so no GitHub API token or
  full clone is needed. The file list for an app comes from that app's upstream
  metadata.json (storage/data/icon/readme/screenshots), plus its ChangeLog.

  Modules are handled too: the fork's modules/ predates current upstream, and a
  refreshed app that require()s a module we carry an old copy of will break, so
  every module an updated app requires is compared and pulled as well.
*/

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const UPSTREAM = "https://raw.githubusercontent.com/espruino/BangleApps/master";

// Apps that belong to this fork and must never be overwritten from upstream
const LOCAL_APPS = ["rareBit"];

const args = process.argv.slice(2);
const PULL = args.includes("--pull");
const ALL = args.includes("--all");
const ONLY = args.reduce((a, v, i) => (args[i - 1] === "--app" ? a.concat(v) : a), []);

function servedApps() {
  // The set of apps this loader serves is the `restricted` list in apps.json
  const src = fs.readFileSync(path.join(ROOT, "apps.json"), "utf8");
  const m = src.match(/^\s*restricted:\s*(\[[^\]]*\])/m);
  if (!m) throw new Error("no `restricted` list found in apps.json");
  return JSON.parse(m[1]);
}

async function get(url, { optional = false } = {}) {
  const res = await fetch(url);
  if (res.status === 404 && optional) return null;
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return Buffer.from(await res.arrayBuffer());
}

function readLocalJSON(rel) {
  const f = path.join(ROOT, rel);
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, "utf8")) : null;
}

// Every file an app ships, derived from its metadata
function appFiles(meta) {
  const files = new Set(["metadata.json", "ChangeLog"]);
  const add = (v) => { if (typeof v === "string" && v) files.add(v); };
  (meta.storage || []).forEach((s) => add(s.url));
  (meta.data || []).forEach((d) => add(d.url));
  (meta.screenshots || []).forEach((s) => add(s.url));
  [meta.icon, meta.readme, meta.custom, meta.customConnect, meta.interface].forEach(add);
  return [...files];
}

// Optional files: missing upstream copies of these are not an error
const OPTIONAL = (f) => f === "ChangeLog" || /\.(png|jpg|gif)$/i.test(f);

async function fetchApp(id, meta) {
  const written = [];
  for (const f of appFiles(meta)) {
    const body = await get(`${UPSTREAM}/apps/${id}/${f}`, { optional: OPTIONAL(f) });
    if (!body) continue;
    const dest = path.join(ROOT, "apps", id, f);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    const changed = !fs.existsSync(dest) || !fs.readFileSync(dest).equals(body);
    fs.writeFileSync(dest, body);
    written.push({ f, changed });
  }
  // Drop files the fork carries that upstream no longer ships (e.g. stale
  // .info files) - but only ones we know are generated, never unknown extras.
  const info = path.join(ROOT, "apps", id, `${id}.info`);
  if (fs.existsSync(info)) fs.unlinkSync(info);
  return written;
}

function requiredModules(id) {
  const dir = path.join(ROOT, "apps", id);
  const mods = new Set();
  for (const f of fs.readdirSync(dir)) {
    if (!/\.(js|ts)$/.test(f)) continue;
    // strip line comments first - several apps mention require("x") in a comment
    const src = fs.readFileSync(path.join(dir, f), "utf8").replace(/^\s*\/\/.*$/gm, "");
    for (const m of src.matchAll(/require\(\s*["']([^"']+)["']\s*\)/g)) mods.add(m[1]);
  }
  return [...mods];
}

// Built into the Espruino firmware, or generated by the loader - never
// files in modules/, so there is nothing to compare them against
const BUILTIN = new Set(["Storage", "heatshrink", "Flash", "locale"]);

async function syncModule(name) {
  const rel = `modules/${name}.js`;
  const body = await get(`${UPSTREAM}/${rel}`, { optional: true });
  if (!body) return null; // not a modules/ file (firmware builtin or app-provided)
  const dest = path.join(ROOT, rel);
  const had = fs.existsSync(dest);
  const same = had && fs.readFileSync(dest).equals(body);
  if (!same && PULL) {
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, body);
  }
  return { name, status: same ? "current" : had ? "stale" : "missing" };
}

const cmp = (a, b) => {
  const pa = String(a).split("."), pb = String(b).split(".");
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (parseInt(pa[i], 10) || 0) - (parseInt(pb[i], 10) || 0);
    if (d) return d;
  }
  return 0;
};

(async () => {
  let ids = servedApps().filter((id) => !LOCAL_APPS.includes(id));
  if (ONLY.length) ids = ids.filter((id) => ONLY.includes(id));

  const stale = [];
  console.log("app          local    upstream  status");
  console.log("--------------------------------------");
  for (const id of ids) {
    const local = readLocalJSON(`apps/${id}/metadata.json`);
    const up = JSON.parse((await get(`${UPSTREAM}/apps/${id}/metadata.json`)).toString());
    const behind = ALL || cmp(local ? local.version : "0", up.version) < 0;
    if (behind) stale.push({ id, meta: up, from: local && local.version, to: up.version });
    console.log(
      `${id.padEnd(12)} ${String(local && local.version).padEnd(8)} ${String(up.version).padEnd(9)} ` +
      (behind ? "OUT OF DATE" : "up to date"));
  }

  if (!stale.length) { console.log("\nAll served apps are current."); return; }
  if (!PULL) {
    console.log(`\n${stale.length} app(s) out of date. Re-run with --pull to update.`);
    return;
  }

  console.log("\nPulling:");
  const mods = new Set();
  for (const { id, meta, from, to } of stale) {
    const written = await fetchApp(id, meta);
    console.log(`  ${id} ${from} -> ${to} (${written.filter((w) => w.changed).length}/${written.length} files changed)`);
    requiredModules(id).forEach((m) => { if (!BUILTIN.has(m)) mods.add(m); });
  }

  console.log("\nModules required by updated apps:");
  for (const name of [...mods].sort()) {
    const r = await syncModule(name);
    if (!r) console.log(`  ${name.padEnd(14)} not a modules/ file (firmware builtin or app-provided)`);
    else console.log(`  ${r.name.padEnd(14)} ${r.status === "current" ? "current" : `${r.status} -> pulled`}`);
  }

  console.log("\nDone. Run `node bin/sanitycheck.js` and `npm run lint-apps` before committing.");
})().catch((e) => { console.error(e.message); process.exit(1); });
